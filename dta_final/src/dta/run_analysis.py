def case_study(ds: str, n_cases: int = 3, seed: int = SPLIT_SEEDS[0]) -> pd.DataFrame:
    """Recommendations for a few drugs, predicted from a reloaded checkpoint.

    Cases are chosen to span regimes rather than to flatter the model: the
    most promiscuous drug, the most selective one with a genuinely strong
    best hit, and the one with the least evidence.  A case study of three
    successes would say less than one that includes the boundary.
    """
    proc, ctx = _context(ds)
    pairs, nl, nt = proc["pairs"], proc["n_lig"], proc["n_tgt"]
    a = S.load_split(ds, "S1_pair", seed)
    tr, va, te = pairs[a == "train"], pairs[a == "val"], pairs[a == "test"]

    model = M.BiasedMF(**_best_params(ds, "S1_pair", "M2_biased_mf")).fit(tr, nl, nt, val=va)
    ckpt = MODELS / f"{ds}_mf.npz"
    model.save(ckpt, dataset=ds)
    loaded = M.BiasedMF.load(ckpt)

    # The reload check: identical, not merely close.
    assert np.array_equal(model.predict(te), loaded.predict(te)), "checkpoint did not round-trip"

    # A case is only informative if the drug has enough held-out targets to
    # rank. On KIBA the median drug has ~31 measurements, so 15% of them is
    # four or five candidates, and a drug with one candidate cannot be
    # ranked at all. Restrict to drugs with a reasonable test set, then pick
    # the extremes within that.
    n_test_per_lig = te.groupby("lig_idx").size()
    min_candidates = int(max(5, n_test_per_lig.quantile(0.75)))
    eligible = n_test_per_lig[n_test_per_lig >= min_candidates].index

    stats = tr.groupby("lig_idx").agg(
        n_train=("score", "size"), mean=("score", "mean"), best=("score", "max"))
    stats = stats.loc[stats.index.intersection(eligible)]
    if stats.empty:  # fall back to whatever has the most candidates
        stats = tr.groupby("lig_idx").agg(
            n_train=("score", "size"), mean=("score", "mean"), best=("score", "max"))
        stats = stats.loc[stats.index.intersection(n_test_per_lig.nlargest(20).index)]
    picks = {
        "most promiscuous (highest mean affinity)": int(stats["mean"].idxmax()),
        "selective but potent (low mean, strong best)":
            int((stats["best"] - stats["mean"]).idxmax()),
        "least evidence (fewest training pairs)": int(stats["n_train"].idxmin()),
    }

    ligands = proc["ligands"].set_index("lig_idx")

    # The brief names three ligands per dataset and asks for them specifically.
    # They take precedence over the heuristic picks above, which stay on as
    # extra cases: between them they span promiscuity on DAVIS and measurement
    # density on KIBA, which is the spread the brief asks the cases to cover.
    by_source_id = {str(v): int(k) for k, v in ligands["ligand_id_first"].items()}
    briefed = [i for i in SUGGESTED_CASE_LIGANDS.get(ds, []) if i in by_source_id]
    picks = {
        **{f"named in the project brief ({i})": by_source_id[i] for i in briefed},
        **picks,
    }
    n_cases = max(n_cases, len(briefed))
    rows, detail = [], []
    for reason, lig in list(picks.items())[:n_cases]:
        sub = te[te.lig_idx == lig].copy()
        if not len(sub):
            continue
        sub["predicted"] = loaded.predict(sub)
        sub = sub.sort_values("predicted", ascending=False)
        truth = sub["score"].to_numpy()
        best_true = truth.max()
        sub["is_best"] = sub["score"] == best_true
        sub["verdict"] = np.where(sub["is_best"], "correct", "wrong")
        rank = int(np.argmax(sub["is_best"].to_numpy())) + 1

        d = sub.head(10)[["target_id", "predicted", "score", "verdict"]].copy()
        d.insert(0, "rank", np.arange(1, len(d) + 1))
        d.insert(0, "ligand_id", ligands.loc[lig, "ligand_id_first"])
        detail.append(d)

        rows.append({
            "dataset": ds,
            "ligand_id": ligands.loc[lig, "ligand_id_first"],
            "why_chosen": reason,
            "n_test_candidates": int(len(sub)),
            "true_best_score": float(best_true),
            "rank_of_true_best": rank,
            "mse": MT.mse(truth, sub["predicted"].to_numpy()),
            "ci": MT.concordance_index(truth, sub["predicted"].to_numpy()),
        })

    summary = pd.DataFrame(rows)
    if len(summary):
        summary.to_csv(TABLES / f"case_summary_{ds}.csv", index=False)
        pd.concat(detail, ignore_index=True).to_csv(TABLES / f"case_detail_{ds}.csv", index=False)
    return summary


# ---------------------------------------------------------------------------
# Which protein representation, and does mixup help?
# ---------------------------------------------------------------------------


def representation_ablation(ds: str, seeds=SPLIT_SEEDS) -> pd.DataFrame:
    """Cold-target performance of the feature models across protein representations.

    The feature-based models were originally wired to amino-acid composition, the
    cheapest of the five descriptors available, and that choice alone accounted for
    most of the gap between them and the kernel methods.  Holding the model, split
    and seed fixed and varying only the representation separates the two.

    GBA-Mixup is varied on the same axis, because interpolating between feature
    vectors can only work where the representation is locally linear in affinity,
    so the two questions are really one.
    """
    from .kernels import TARGET_BLOCKS

    proc, ctx = _context(ds)
    pairs, nl, nt = proc["pairs"], proc["n_lig"], proc["n_tgt"]
    blocks = [b for b in TARGET_BLOCKS if b in ctx["features"]]
    rows = []
    for seed in seeds:
        a = S.load_split(ds, "S3_new_target", seed)
        tr, va, te = pairs[a == "train"], pairs[a == "val"], pairs[a == "test"]
        if not len(te):
            continue
        for block in blocks:
            for mixup in (None, "drug"):
                model = C.ContentRegressor(target_block=block, mixup=mixup)
                model.fit(tr, nl, nt, val=va, **ctx)
                res = MT.evaluate(te, model.predict(te), ds, seed=seed)
                res.update({
                    "dataset": ds, "seed": seed, "representation": block,
                    "n_dimensions": int(ctx["features"][block].shape[1]),
                    "mixup": mixup or "none",
                    "n_virtual": getattr(model, "n_virtual_", 0),
                })
                rows.append(res)
    out = pd.DataFrame(rows)
    if len(out):
        out.to_csv(TABLES / f"representation_{ds}.csv", index=False)
    return out


# ---------------------------------------------------------------------------


def main(which=None) -> None:
    which = which or list(DATASETS)
    buckets = {}
    for ds in which:
        print(f"\n=== {ds.upper()}")
        print("  representation ablation")
        rep = representation_ablation(ds)
        if len(rep):
            summary = (rep.groupby(["representation", "mixup"])
                       .agg(mse=("mse", "mean"), ci_per_ligand=("ci_per_ligand", "mean"))
                       .unstack().round(4))
            print(summary.to_string())
        print("  lookup check")
        lc = lookup_check(ds)
        print(f"    corr(true residual, predicted interaction) = "
              f"{lc['correlation_true_residual_vs_predicted_interaction']:.3f}")
        print("  case study")
        cs = case_study(ds)
        if len(cs):
            print(cs[["ligand_id", "why_chosen", "n_test_candidates",
                      "rank_of_true_best"]].to_string(index=False))
        print("  similarity buckets")
        b = similarity_buckets(ds)
        buckets[ds] = b
        if len(b):
            print(b.groupby(["bucket", "model"], observed=False)["ci_per_ligand"]
                  .mean().unstack().round(3).to_string())

    if any(len(b) for b in buckets.values()):
        P.use_style()
        p = P.similarity_buckets({k: v for k, v in buckets.items() if len(v)})
        print(f"\n  wrote {p.relative_to(RESULTS.parent)}")


if __name__ == "__main__":
    main([a for a in sys.argv[1:] if not a.startswith("--")] or None)
