# Not a lookup
# ---------------------------------------------------------------------------


def lookup_check(ds: str, seed: int = SPLIT_SEEDS[0]) -> dict:
    """Does the interaction term carry knowledge that transfers to unseen pairs?"""
    proc, ctx = _context(ds)
    pairs, nl, nt = proc["pairs"], proc["n_lig"], proc["n_tgt"]
    a = S.load_split(ds, "S1_pair", seed)
    tr, va, te = pairs[a == "train"], pairs[a == "val"], pairs[a == "test"]

    bias = M.BiasOnly(lam=1.0).fit(tr, nl, nt)
    mf = M.BiasedMF(**_best_params(ds, "S1_pair", "M2_biased_mf")).fit(tr, nl, nt, val=va)

    li, ti = te["lig_idx"].to_numpy(), te["tgt_idx"].to_numpy()
    true_resid = te["score"].to_numpy(dtype=float) - bias._raw(li, ti)
    predicted_interaction = mf.predict_interaction(te)
    r = float(np.corrcoef(true_resid, predicted_interaction)[0, 1])

    out = {
        "dataset": ds,
        "correlation_true_residual_vs_predicted_interaction": r,
        "n_test_pairs": int(len(te)),
        "mse_bias_only": MT.mse(te["score"], bias.predict(te)),
        "mse_with_interaction": MT.mse(te["score"], mf.predict(te)),
        "note": ("every pair here is absent from training; a lookup table returns "
                 "nothing for them and its best fallback is the drug mean"),
    }
    with open(RESULTS / f"lookup_check_{ds}.json", "w") as fh:
        json.dump(out, fh, indent=2)
    return out


