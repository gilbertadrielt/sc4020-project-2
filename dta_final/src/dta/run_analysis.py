# Where cold-start stops working
# ---------------------------------------------------------------------------


def similarity_buckets(ds: str, seeds=SPLIT_SEEDS) -> pd.DataFrame:
    """Cold-target performance split by distance to the nearest training protein.

    All models share one set of bucket edges (``analysis.BUCKET_EDGES``).
    Two people using different cuts will draw different conclusions from the
    same model, so the cuts live in one place.
    """
    proc, ctx = _context(ds)
    pairs, nl, nt = proc["pairs"], proc["n_lig"], proc["n_tgt"]
    rows = []
    for seed in seeds:
        a = S.load_split(ds, "S3_new_target", seed)
        tr, va, te = pairs[a == "train"], pairs[a == "val"], pairs[a == "test"]
        if not len(te):
            continue
        knn = C.SequenceKNN(axis="target", **_best_params(ds, "S3_new_target", "C1_sequence_knn"))
        knn.fit(tr, nl, nt, val=va, **ctx)
        max_sim = knn.max_similarity_to_train(te)

        candidates = {
            "C0_fallback": C.ColdFallback(),
            "C1_sequence_knn": knn,
            "M5_kronrls": KronRLS(**_best_params(ds, "S3_new_target", "M5_kronrls")),
        }
        for name, model in candidates.items():
            if not hasattr(model, "score_min_"):
                model.fit(tr, nl, nt, val=va, **ctx)
            b = A.similarity_buckets(te, max_sim, model.predict(te), ds)
            b["model"] = name
            b["seed"] = seed
            rows.append(b)
    out = pd.concat(rows, ignore_index=True) if rows else pd.DataFrame()
    if len(out):
        out.to_csv(TABLES / f"buckets_{ds}.csv", index=False)
    return out


