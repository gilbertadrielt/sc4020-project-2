#: Ligands the project brief names for the Task 2 case study. All six survive
#: deduplication as the representative identifier of their chemistry, so they
#: can be looked up directly.
SUGGESTED_CASE_LIGANDS = {
    "davis": ["10127622", "11338033", "44259"],
    "kiba": ["CHEMBL1967538", "CHEMBL2004544", "CHEMBL565612"],
}


def _context(ds):
    proc = D.load_processed(ds)
    return proc, {"kernels": K.build_kernels(ds, proc),
                  "features": K.build_features(ds, proc), "dataset": ds}


def _best_params(ds, setting, model):
    """Read back the hyperparameters the sweep chose on validation."""
    p = TABLES / f"tuning_{ds}_{setting}.csv"
    if not p.exists():
        return {}
    t = pd.read_csv(p)
    t = t[(t.model == model)].dropna(subset=["val_mse"])
    if not len(t):
        return {}
    row = t.loc[t.val_mse.idxmin()]
    skip = {"dataset", "setting", "model", "val_mse", "seconds", "error"}
    out = {}
    for c in t.columns:
        if c in skip or pd.isna(row[c]):
            continue
        v = row[c]
        out[c] = int(v) if float(v).is_integer() and c in ("k",) else float(v)
    return out


