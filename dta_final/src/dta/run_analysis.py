"""Post-hoc analyses that need fitted models rather than just metrics.

Three things the results table cannot show on its own:

``similarity_buckets``
    Where borrowing from relatives stops working.  A single cold-start
    average hides the fact that the method is excellent on near-homologues
    and close to useless on orphans, and that distinction is the honest
    headline for the limitations section.

``lookup_check``
    Evidence that the model is not a disguised lookup of known answers.  On
    held-out pairs the true residual (truth minus what a bias model
    predicts) is correlated with the predicted interaction.  A model that
    had merely memorised would show nothing there.

``case_study``
    Recommendations for individual drugs, generated by reloading the saved
    checkpoint from disk rather than from the model still in memory, which
    is also the reload check.
"""
from __future__ import annotations

