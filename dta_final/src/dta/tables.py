"""Turn the result CSVs into LaTeX, ready to \\input into the report.

No number in the report should be one somebody typed.  Re-running an
experiment and recompiling then keeps the text and the results in step
automatically, and a stale table becomes impossible rather than merely
unlikely.

Usage in the report::

    \\usepackage{booktabs}
    \\begin{table}[t]
      \\centering
      \\caption{Held-out results, mean over five seeds.}
      \\input{tables/tex/results_davis_S1_pair.tex}
    \\end{table}
"""
from __future__ import annotations

import sys

import numpy as np
import pandas as pd

from .config import DATASETS, TABLES

TEX = TABLES / "tex"
TEX.mkdir(parents=True, exist_ok=True)

MODEL_LABEL = {
    "B0_global_mean": "B0 Global mean",
    "B1_ligand_mean": "B1 Drug mean (CF fallback)",
    "B2_target_mean": "B2 Target mean",
    "B3_bias_only": r"B3 Bias only ($\mu + b_i + c_j$)",
    "M1_item_knn": "M1 Item-based kNN",
    "M2_biased_mf": "M2 Biased MF",
    "M3_knn_mf_blend": "M3 kNN + MF blend",
    "M4_tobit_mf": "M4 MF, censored loss",
    "M4b_tobit_squared": "M4b MF, squared loss (control)",
    "M5_kronrls": "M5 KronRLS",
    "M6_kronrls_mkl": "M6 KronRLS, multiple kernels",
    "C0_fallback": "C0 Fallback",
    "C1_sequence_knn": "C1 Guilt-by-association kNN",
    "C1_structure_knn": "C1 Structure kNN",
    "C2_factor_map": "C2 Sequence to MF factors",
    "C3_content_reg": "C3 Content regression",
    "C4_gated_blend": "C4 Similarity-gated blend",
}

SETTING_LABEL = {
    "S1_pair": "S1, random held-out pairs",
    "S2_new_drug": "S2, unseen drugs",
    "S3_new_target": "S3, unseen targets",
    "S4_both_new": "S4, both unseen",
}


def _write(df: pd.DataFrame, name: str, caption: str = "", floatfmt: str = "%.3f") -> None:
    path = TEX / f"{name}.tex"
    body = df.to_latex(index=False, escape=False,
                       float_format=lambda v: floatfmt % v,
                       column_format="l" + "r" * (df.shape[1] - 1))
    path.write_text(f"% generated by dta.tables -- do not edit\n% {caption}\n{body}")
    print(f"  wrote {path.relative_to(TABLES.parent.parent)}")


def _pm(mean, std, fmt="%.3f") -> str:
    if pd.isna(mean):
        return "--"
    if pd.isna(std):
        return fmt % mean
    return f"{fmt % mean} $\\pm$ {fmt % std}"


