RESULT_COLUMNS = [
    ("mse", "MSE", "%.3f"),
    ("mse_strong", "MSE strong", "%.2f"),
    ("ci", "CI", "%.3f"),
    ("ci_per_ligand", "CI per-drug", "%.3f"),
    ("hit_at_1", "Hit@1", "%.3f"),
    ("mrr", "MRR", "%.3f"),
]


def results_tables(summary: pd.DataFrame, which) -> None:
    """One table per dataset and regime, with the spread across seeds."""
    for ds in which:
        for setting in SETTING_LABEL:
            d = summary[(summary.dataset == ds) & (summary.setting == setting)]
            if not len(d):
                continue
            rows = []
            for r in d.itertuples():
                row = {"Model": MODEL_LABEL.get(r.model, r.model.replace("_", " "))}
                for key, label, fmt in RESULT_COLUMNS:
                    m, s = f"{key}_mean", f"{key}_std"
                    if m in d.columns:
                        row[label] = _pm(getattr(r, m, np.nan), getattr(r, s, np.nan), fmt)
                if "random_hit_at_1_mean" in d.columns:
                    row["Random Hit@1"] = "%.3f" % getattr(r, "random_hit_at_1_mean", np.nan)
                if "fallback_rate_mean" in d.columns and np.isfinite(
                    getattr(r, "fallback_rate_mean", np.nan)
                ):
                    row["Fallback"] = "%.0f\\%%" % (100 * getattr(r, "fallback_rate_mean"))
                rows.append(row)
            _write(pd.DataFrame(rows), f"results_{ds}_{setting}",
                   f"{ds.upper()}, {SETTING_LABEL[setting]}; mean $\\pm$ sd over seeds", "%s")


def headline_table(summary: pd.DataFrame, which) -> None:
    """One compact table: the best model per regime, next to the fallback.

    This is the table that answers the project in a single block, and the
    one worth putting early in the report.
    """
    rows = []
    for ds in which:
        for setting in SETTING_LABEL:
            d = summary[(summary.dataset == ds) & (summary.setting == setting)]
            if not len(d) or "ci_per_ligand_mean" not in d.columns:
                continue
            base = d[d.model.str.startswith(("B1", "C0"))]
            best = d.loc[d["ci_per_ligand_mean"].idxmax()]
            rows.append({
                "Dataset": ds.upper(),
                "Setting": SETTING_LABEL[setting],
                "Fallback CI per-drug": ("%.3f" % base["ci_per_ligand_mean"].iloc[0]
                                         if len(base) else "--"),
                "Best model": MODEL_LABEL.get(best.model, best.model),
                "Best CI per-drug": "%.3f" % best["ci_per_ligand_mean"],
                # The MSE *of that model*, which is not always the lowest MSE in
                # the regime: ranking and squared error do not always agree, and
                # labelling this "best MSE" would quietly claim they do.
                "Its MSE": "%.3f" % best["mse_mean"],
                "Lowest MSE here": "%.3f" % d["mse_mean"].min(),
            })
    if rows:
        _write(pd.DataFrame(rows), "headline",
               "Best model per regime against the fallback it must beat", "%s")


def tuning_table(which) -> None:
    p = TABLES / "tuning_all.csv"
    if not p.exists():
        return
    t = pd.read_csv(p)
    rows = []
    for ds in which:
        for setting in SETTING_LABEL:
            d = t[(t.dataset == ds) & (t.setting == setting)].dropna(subset=["val_mse"])
            if not len(d):
                continue
            for model, g in d.groupby("model"):
                b = g.loc[g.val_mse.idxmin()]
                params = {c: b[c] for c in g.columns
                          if c not in ("dataset", "setting", "model", "val_mse",
                                       "seconds", "error") and pd.notna(b[c])}
                rows.append({
                    "Dataset": ds.upper(),
                    "Setting": setting.replace("_", " "),
                    "Model": MODEL_LABEL.get(model, model),
                    "Chosen": ", ".join(f"{k}={v:g}" if isinstance(v, (int, float)) else f"{k}={v}"
                                        for k, v in params.items()) or "--",
                    "Val MSE": "%.4f" % b.val_mse,
                })
    if rows:
        _write(pd.DataFrame(rows), "tuning",
               "Hyperparameters chosen on validation; test was never consulted", "%s")


def contribution_template(members=("Member 1", "Member 2", "Member 3", "Member 4")) -> None:
    """The contribution table the brief requires, as a skeleton to fill in."""
    df = pd.DataFrame({
        "Member Name": list(members),
        "Contribution (\\%)": [f"{100 / len(members):.0f}\\%"] * len(members),
        "Justification": ["FILL IN: list of contributions."] * len(members),
    })
    _write(df, "contribution_table", "Required individual contribution claims", "%s")


def main(which=None) -> None:
    which = which or list(DATASETS)
    print("Task 1 tables")
    task1_tables(which)

    p = TABLES / "summary_all.csv"
    if p.exists():
        summary = pd.read_csv(p)
        print("Result tables")
        results_tables(summary, which)
        headline_table(summary, which)
    else:
        print("  (no summary_all.csv yet; run `python -m dta.protocol` first)")

    print("Tuning table")
    tuning_table(which)
    print("Report scaffolding")
    contribution_template()
    print(f"\nAll LaTeX tables are in {TEX}")


if __name__ == "__main__":
    main([a for a in sys.argv[1:] if not a.startswith("--")] or None)
