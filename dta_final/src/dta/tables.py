def task1_tables(which) -> None:
    p = TABLES / "task1_comparison.csv"
    if p.exists():
        df = pd.read_csv(p, index_col=0)
        df.index.name = "Property"
        _write(df.reset_index(), "task1_comparison", "DAVIS and KIBA side by side", "%s")

    for ds in which:
        c = TABLES / f"task1_counts_{ds}.csv"
        if c.exists():
            d = pd.read_csv(c)[["level", "ligands", "targets", "observed_pairs",
                                "matrix_cells", "density"]]
            d.columns = ["Level", "Drugs", "Targets", "Observed pairs", "Cells", "Density"]
            _write(d, f"task1_counts_{ds}", f"{ds.upper()} counts before and after merging")

        cl = TABLES / f"task1_cleaning_{ds}.csv"
        if cl.exists():
            d = pd.read_csv(cl)[["step", "pairs_remaining", "note"]]
            d.columns = ["Cleaning step", "Pairs remaining", "Note"]
            _write(d, f"task1_cleaning_{ds}", f"{ds.upper()} cleaning log", "%s")

        v = TABLES / f"task1_variance_{ds}.csv"
        if v.exists():
            d = pd.read_csv(v)[["component", "variance_explained"]]
            d.columns = ["Component", "Share of variance"]
            _write(d, f"task1_variance_{ds}", f"{ds.upper()} variance decomposition")


